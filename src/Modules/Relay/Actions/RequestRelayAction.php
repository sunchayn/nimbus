<?php

namespace Sunchayn\Nimbus\Modules\Relay\Actions;

use Carbon\CarbonImmutable;
use GuzzleHttp\Cookie\SetCookie;
use GuzzleHttp\Psr7\MultipartStream;
use GuzzleHttp\TransferStats;
use Illuminate\Container\Container;
use Illuminate\Cookie\CookieValuePrefix;
use Illuminate\Http\Client\PendingRequest;
use Illuminate\Http\Client\Response;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Arr;
use Illuminate\Support\Facades\Http;
use RuntimeException;
use Sunchayn\Nimbus\Modules\Config\ActiveApplicationResolver;
use Sunchayn\Nimbus\Modules\Config\Enums\EnvironmentIdEnum;
use Sunchayn\Nimbus\Modules\Relay\DataTransferObjects\RelayedRequestResponseData;
use Sunchayn\Nimbus\Modules\Relay\DataTransferObjects\RequestRelayData;
use Sunchayn\Nimbus\Modules\Relay\Responses\DumpAndDieResponse;
use Sunchayn\Nimbus\Modules\Relay\Services\Authorization\Handlers\AuthorizationHandlerFactory;
use Sunchayn\Nimbus\Modules\Relay\ValueObjects\DownloadResponseBody;
use Sunchayn\Nimbus\Modules\Relay\ValueObjects\PrintableResponseBody;
use Sunchayn\Nimbus\Modules\Relay\ValueObjects\ResponseCookieValueObject;
use Sunchayn\Nimbus\Modules\Relay\ValueObjects\SentRequest;
use Symfony\Component\HttpFoundation\Response as SymfonyResponse;
use Throwable;

class RequestRelayAction
{
    public const DEFAULT_CONTENT_TYPE = 'application/json';

    public const MICROSECONDS_TO_MILLISECONDS = 1_000_000;

    public const NON_STANDARD_STATUS_CODES = [
        419 => 'Page Expired',
        DumpAndDieResponse::DUMP_AND_DIE_STATUS_CODE => 'dd()',
    ];

    public function __construct(
        private readonly Container $container,
        private readonly AuthorizationHandlerFactory $authorizationHandlerFactory,
        private readonly ActiveApplicationResolver $activeApplicationResolver,
    ) {}

    public function execute(RequestRelayData $requestRelayData): RelayedRequestResponseData
    {
        $pendingRequest = $this->prepareRequest($requestRelayData);

        $authorizationHandler = $this
            ->authorizationHandlerFactory
            ->create($requestRelayData->authorization, $requestRelayData->isCurrentHost);

        $pendingRequest = $authorizationHandler->authorize($pendingRequest);

        $sentRequest = null;

        $pendingRequest = $pendingRequest->withOptions([
            'on_stats' => function (TransferStats $stats) use (&$sentRequest): void {
                $sentRequest = SentRequest::fromPsrRequest($stats->getRequest());
            },
        ]);

        $start = hrtime(true);

        $response = $this->sendPendingRequest($pendingRequest, $requestRelayData);

        $durationInMs = $this->calculateDuration($start);

        $download = DownloadResponseBody::tryFromResponse($response, $requestRelayData->endpoint);

        return new RelayedRequestResponseData(
            statusCode: $response->status(),
            statusText: $this->getStatusTextFromCode($response->status()),
            // The raw bytes of a download are forwarded separately and never printed.
            body: $download instanceof DownloadResponseBody
                ? new PrintableResponseBody('')
                : PrintableResponseBody::fromResponse($response),
            headers: $response->headers(),
            durationMs: $durationInMs,
            timestamp: CarbonImmutable::now()->getTimestamp(),
            cookies: $this->processCookies($response->toPsrResponse()->getHeader('Set-Cookie'), $requestRelayData->isCurrentHost),
            download: $download,
            sent: $sentRequest,
        );
    }

    private function prepareRequest(RequestRelayData $requestRelayData): PendingRequest
    {
        $contentType = $requestRelayData->headers['content-type'] ?? self::DEFAULT_CONTENT_TYPE;

        $queryParameters = $requestRelayData->queryParameters;
        $requestBody = $requestRelayData->body;

        if (is_array($requestBody) && in_array($requestRelayData->method, ['get', 'head'], true)) {
            $queryParameters = array_merge(
                $queryParameters,
                $requestBody,
            );

            $requestBody = [];
        }

        $headers = $requestRelayData->headers;

        $mediaType = strtolower(trim(explode(';', $contentType)[0]));

        $multipartBody = is_array($requestBody) && $requestBody !== [] && $mediaType === 'multipart/form-data'
            ? $requestBody
            : null;

        // The body call below sets Content-Type itself, so a copy in the headers would be sent twice.
        // For multipart it also matters because the boundary is generated by the HTTP client.
        if ($multipartBody !== null || $requestBody !== []) {
            $headers = array_filter($headers, fn (string $name): bool => strtolower($name) !== 'content-type', ARRAY_FILTER_USE_KEY);
        }

        // Auto-inject CSRF token header if not explicitly provided
        $hasCsrfHeader = array_key_exists('X-CSRF-TOKEN', $headers) || array_key_exists('X-XSRF-TOKEN', $headers);

        if (! $hasCsrfHeader && $requestRelayData->isCurrentHost) {
            $csrfToken = $this->resolveCsrfToken();

            if ($csrfToken !== null) {
                $headers['X-CSRF-TOKEN'] = $csrfToken;
            }
        }

        // Add transaction mode header if enabled
        if ($requestRelayData->transactionMode) {
            $headers['x-nimbus-transaction-mode'] = '1';
        }

        return Http::withOptions(
            [
                'verify' => $requestRelayData->verifySsl ?? $this->shouldVerifySsl($requestRelayData),
                'allow_redirects' => $requestRelayData->followRedirects,
            ],
        )
            ->timeout($requestRelayData->timeout)
            ->withHeaders($headers)
            ->withQueryParameters($queryParameters)
            ->when(
                $multipartBody !== null,
                fn (PendingRequest $pendingRequest): PendingRequest => $this->attachMultipartBody($pendingRequest, $multipartBody ?? []),
            )
            ->when(
                $requestBody !== [] && $multipartBody === null,
                function (PendingRequest $pendingRequest) use ($requestBody, $contentType) {
                    $body = match (true) {
                        is_string($requestBody) => $requestBody,
                        str_starts_with(strtolower($contentType), 'application/x-www-form-urlencoded') => http_build_query($requestBody),
                        default => json_encode($requestBody) ?: throw new RuntimeException('Cannot parse body.'),
                    };

                    return $pendingRequest->withBody(
                        $body,
                        contentType: $contentType,
                    );
                },
            );
    }

    /**
     * Sends every field and file as its own multipart part.
     *
     * The body is built here because the boundary must match the Content-Type header.
     *
     * @param  array<array-key, mixed>  $body
     */
    private function attachMultipartBody(PendingRequest $pendingRequest, array $body): PendingRequest
    {
        $elements = [];

        foreach ($this->flattenMultipartFields($body) as [$name, $value]) {
            $elements[] = $value instanceof UploadedFile
                ? [
                    'name' => $name,
                    'contents' => fopen($value->getRealPath(), 'r'),
                    'filename' => $value->getClientOriginalName(),
                    'headers' => ['Content-Type' => $value->getClientMimeType()],
                ]
                : ['name' => $name, 'contents' => (string) $value];
        }

        $multipartStream = new MultipartStream($elements);

        return $pendingRequest->withBody($multipartStream, 'multipart/form-data; boundary='.$multipartStream->getBoundary());
    }

    /**
     * Turns nested arrays back into bracket names, such as photos[] and user[avatar].
     *
     * @param  array<array-key, mixed>  $fields
     * @return list<array{string, mixed}>
     */
    private function flattenMultipartFields(array $fields, ?string $prefix = null): array
    {
        $flattened = [];
        $isList = $prefix !== null && array_is_list($fields);

        foreach ($fields as $key => $value) {
            $name = match (true) {
                $prefix === null => (string) $key,
                $isList => $prefix.'[]',
                default => $prefix.'['.$key.']',
            };

            if (is_array($value)) {
                array_push($flattened, ...$this->flattenMultipartFields($value, $name));

                continue;
            }

            $flattened[] = [$name, $value];
        }

        return $flattened;
    }

    /**
     * Calculates request duration in milliseconds with precision formatting.
     *
     * Uses high-resolution time for accurate microsecond measurements,
     * formatted to 2 decimal places for readability.
     */
    private function calculateDuration(int $startTime): float
    {
        return (float) number_format(
            (hrtime(true) - $startTime) / self::MICROSECONDS_TO_MILLISECONDS,
            2,
            thousands_separator: ''
        );
    }

    private function shouldVerifySsl(RequestRelayData $requestRelayData): bool
    {
        if ($requestRelayData->environment === EnvironmentIdEnum::Production->value) {
            return true;
        }

        if ($requestRelayData->environment !== EnvironmentIdEnum::Current->value) {
            return false;
        }

        $current = $this->activeApplicationResolver->getEnvironments()[0];

        return $current->detected === EnvironmentIdEnum::Production->value;
    }

    /**
     * Processes Set-Cookie headers into structured cookie objects.
     *
     * Cookies are URL-decoded and prefixed with Laravel's encryption key
     * to match the application's cookie handling behavior.
     *
     * @param  string[]  $setCookieHeaders
     * @param  bool  $decrypt  Decryption relies on the host app key, so it only applies to the current host.
     * @return ResponseCookieValueObject[]
     */
    private function processCookies(array $setCookieHeaders, bool $decrypt): array
    {
        return Arr::map(
            $setCookieHeaders,
            function (string $cookieString) use ($decrypt): ResponseCookieValueObject {
                $setCookie = SetCookie::fromString($cookieString);

                return new ResponseCookieValueObject(
                    key: $setCookie->getName(),
                    rawValue: urldecode($setCookie->getValue() ?? ''),
                    prefix: CookieValuePrefix::create(
                        $setCookie->getName(),
                        $this->container->get('encrypter')->getKey()
                    ),
                    decrypt: $decrypt,
                );
            },
        );
    }

    /**
     * Maps HTTP status codes to human-readable status text.
     *
     * Includes Laravel-specific status codes like 419 (Method Not Allowed)
     * that aren't part of the standard HTTP specification.
     */
    private function getStatusTextFromCode(int $statusCode): string
    {
        $statusCodeToTextMapping = SymfonyResponse::$statusTexts + self::NON_STANDARD_STATUS_CODES;

        return $statusCodeToTextMapping[$statusCode] ?? 'Non-standard Status Code.';
    }

    private function sendPendingRequest(PendingRequest $pendingRequest, RequestRelayData $requestRelayData): Response
    {
        $response = $pendingRequest->send(
            method: $requestRelayData->method,
            url: $requestRelayData->endpoint,
        );

        if (! $response->serverError()) {
            return $response;
        }

        if (! str_contains($response->body(), 'Sfdump = window.Sfdump')) {
            return $response;
        }

        return new DumpAndDieResponse($response->toPsrResponse());
    }

    private function resolveCsrfToken(): ?string
    {
        try {
            $token = csrf_token();

            return filled($token) ? $token : null;
        } catch (Throwable) {
            return null;
        }
    }
}
